// --- CURRENCY HANDLERS ---
function applyCurrencyPreference(currCode, showFeedback = true) {
  const cfg = window.CURRENCY_CONFIGS[currCode] || window.CURRENCY_CONFIGS.INR;
  const previousSymbol = window.currentCurrencySymbol || '₹';
  window.PORTAL_PREFERENCES.currency = currCode;
  window.currentCurrencySymbol = cfg.symbol;
  localStorage.setItem('ankurmitra_currency', currCode);

  const sampleEl = document.getElementById('currencyPreviewSample');
  if (sampleEl) sampleEl.textContent = cfg.formatSample;

  const sel = document.getElementById('portalPrefCurrency');
  if (sel && sel.value !== currCode) sel.value = currCode;

  replaceCurrencyAcrossDom(previousSymbol, cfg.symbol);

  if (typeof renderToolsTable === 'function') renderToolsTable();
  if (typeof renderMandiTable === 'function') renderMandiTable();
  if (typeof renderOffersTable === 'function') renderOffersTable();

  if (showFeedback && typeof showToast === 'function') {
    showToast('Currency updated to ' + cfg.name + '. Figures synchronized.', 'success');
  }
}

function replaceCurrencyAcrossDom(fromSym, toSym) {
  if (fromSym === toSym) return;
  const escapedFrom = fromSym.trim().replace(/[.*+?^$\\{}()|[\\]\\\\]/g, '\\\\$&');
  const regex = new RegExp(escapedFrom + '(?=\\\\s*[0-9])', 'g');

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while ((node = walker.nextNode())) {
    if (node.nodeValue && regex.test(node.nodeValue)) {
      node.nodeValue = node.nodeValue.replace(regex, toSym.trim());
    }
  }
}

// --- TIMEZONE HANDLERS ---
function applyTimezonePreference(tz, showFeedback = true) {
  const cfg = window.TIMEZONE_CONFIGS[tz] || window.TIMEZONE_CONFIGS['Asia/Kolkata'];
  window.PORTAL_PREFERENCES.timezone = tz;
  localStorage.setItem('ankurmitra_timezone', tz);

  updateSettingsLiveClock(tz);

  const sel = document.getElementById('portalPrefTimezone');
  if (sel && sel.value !== tz) sel.value = tz;

  if (showFeedback && typeof showToast === 'function') {
    showToast('Timezone synchronized to ' + cfg.name + '.', 'success');
  }
}

function updateSettingsLiveClock(tz) {
  const clockEl = document.getElementById('settingsLiveClockDisplay');
  const tzLabelEl = document.getElementById('settingsTzLabelDisplay');
  if (!clockEl) return;
  try {
    const now = new Date();
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: tz || window.PORTAL_PREFERENCES.timezone,
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: true,
      weekday: 'short',
      year: 'numeric',
      month: 'short',
      day: 'numeric'
    });
    clockEl.textContent = formatter.format(now);
    if (tzLabelEl) {
      const cfg = window.TIMEZONE_CONFIGS[tz || window.PORTAL_PREFERENCES.timezone] || window.TIMEZONE_CONFIGS['Asia/Kolkata'];
      tzLabelEl.textContent = cfg.name;
    }
  } catch (err) {
    clockEl.textContent = new Date().toLocaleTimeString();
  }
}

// --- MASTER PREFERENCES INIT & SAVE ---
function saveAllPortalPreferences() {
  const lang = document.getElementById('portalPrefLanguage')?.value || 'en';
  const tz = document.getElementById('portalPrefTimezone')?.value || 'Asia/Kolkata';
  const curr = document.getElementById('portalPrefCurrency')?.value || 'INR';

  applyLanguagePreference(lang, false);
  applyTimezonePreference(tz, false);
  applyCurrencyPreference(curr, false);

  if (typeof showToast === 'function') {
    showToast('All Portal Preferences (Theme, Language, Timezone, Currency) saved & applied.', 'success');
  }
}

function resetPortalPreferencesToDefaults() {
  setPortalTheme('light', false);
  applyLanguagePreference('en', false);
  applyTimezonePreference('Asia/Kolkata', false);
  applyCurrencyPreference('INR', false);

  initPortalPreferencesUi();
  if (typeof showToast === 'function') {
    showToast('Reset all portal preferences to standard defaults.', 'info');
  }
}

function initPortalPreferencesUi() {
  // 1. Theme
  const savedTheme = localStorage.getItem('ankurmitra_theme') || 'light';
  setPortalTheme(savedTheme, false);

  // 2. Language
  const savedLang = localStorage.getItem('ankurmitra_language') || 'en';
  const langSel = document.getElementById('portalPrefLanguage');
  if (langSel) langSel.value = savedLang;
  applyLanguagePreference(savedLang, false);

  // 3. Timezone
  const savedTz = localStorage.getItem('ankurmitra_timezone') || 'Asia/Kolkata';
  const tzSel = document.getElementById('portalPrefTimezone');
  if (tzSel) tzSel.value = savedTz;
  applyTimezonePreference(savedTz, false);

  // 4. Currency
  const savedCurr = localStorage.getItem('ankurmitra_currency') || 'INR';
  const currSel = document.getElementById('portalPrefCurrency');
  if (currSel) currSel.value = savedCurr;
  applyCurrencyPreference(savedCurr, false);

  // 5. Clock interval
  updateSettingsLiveClock(savedTz);
  if (!window.settingsClockInterval) {
    window.settingsClockInterval = setInterval(() => {
      updateSettingsLiveClock(window.PORTAL_PREFERENCES.timezone);
    }, 1000);
  }
}

// Initialize on DOM load
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initPortalPreferencesUi);
} else {
  initPortalPreferencesUi();
}
